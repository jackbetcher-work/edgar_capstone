export function formatPeriodEndShort(isoDate: string | null | undefined): string {
  if (!isoDate) return ''
  const trimmed = isoDate.trim()
  const match = /^(\d{4})-(\d{2})-(\d{2})/.exec(trimmed)
  if (!match) return trimmed
  const monthNames = [
    'Jan',
    'Feb',
    'Mar',
    'Apr',
    'May',
    'Jun',
    'Jul',
    'Aug',
    'Sep',
    'Oct',
    'Nov',
    'Dec',
  ]
  const monthIdx = Number(match[2]) - 1
  const label = monthNames[monthIdx]
  if (!label) return trimmed
  return `${label} ${match[1]}`
}

export interface ParsedInlineCitationToken {
  rawMatch: string
  ticker: string
  fiscalYear: number
  sectionLabel: string
  chunkId: string
  url: string
}

export interface ParsedInlineXbrlToken {
  rawMatch: string
  ticker: string
  fiscalYear: number
  xbrlConcept: string
  accessionNumber: string
  url: string
}

/**
 * Matches canonical inline citations generated by the agent:
 * - Text chunk: [NVDA FY2026 | Item 7 MD&A | NVDA_2026_item_7_0001](https://www.sec.gov/...)
 * - XBRL fact:  [NVDA FY2024 | XBRL us-gaap:Revenues | acc:0001045810-24-000029](https://www.sec.gov/...)
 */
const COMBINED_INLINE_CITATION_RE =
  /\[([A-Z.-]{1,6})\s+FY(\d{4})\s*\|\s*([^|\]]+?)\s*\|\s*([^\]]+?)\]\(([^)]*)\)/g

export type InlineCitationSegment =
  | { type: 'text'; value: string }
  | { type: 'citation'; token: ParsedInlineCitationToken }
  | { type: 'xbrl'; token: ParsedInlineXbrlToken }

export function splitTextByInlineCitations(
  text: string
): InlineCitationSegment[] {
  const segments: InlineCitationSegment[] = []

  let lastIndex = 0
  let match: RegExpExecArray | null
  const regex = new RegExp(COMBINED_INLINE_CITATION_RE.source, 'g')

  while ((match = regex.exec(text)) !== null) {
    if (match.index > lastIndex) {
      segments.push({
        type: 'text',
        value: text.slice(lastIndex, match.index),
      })
    }
    const ticker = match[1].trim()
    const fiscalYear = Number(match[2])
    const middle = match[3].trim()
    const third = match[4].trim()
    const url = match[5].trim()

    if (
      middle.toUpperCase().startsWith('XBRL') ||
      third.toLowerCase().startsWith('acc:')
    ) {
      const concept = middle.replace(/^XBRL\s*/i, '').trim() || 'XBRL'
      const accessionNumber = third.replace(/^acc:/i, '').trim()
      segments.push({
        type: 'xbrl',
        token: {
          rawMatch: match[0],
          ticker,
          fiscalYear,
          xbrlConcept: concept,
          accessionNumber,
          url,
        },
      })
    } else {
      segments.push({
        type: 'citation',
        token: {
          rawMatch: match[0],
          ticker,
          fiscalYear,
          sectionLabel: middle,
          chunkId: third,
          url,
        },
      })
    }
    lastIndex = regex.lastIndex
  }

  if (lastIndex < text.length) {
    segments.push({
      type: 'text',
      value: text.slice(lastIndex),
    })
  }

  return segments
}
