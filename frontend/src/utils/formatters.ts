export interface ParsedInlineCitationToken {
  rawMatch: string
  ticker: string
  fiscalYear: number
  sectionLabel: string
  chunkId: string
  url: string
}

/**
 * Matches canonical inline citations generated by the agent:
 * [NVDA FY2026 | Item 7 MD&A | NVDA_2026_item_7_0001](https://www.sec.gov/...)
 */
const INLINE_CITATION_RE =
  /\[([A-Z.-]{1,6})\s+FY(\d{4})\s*\|\s*([^|\]]+?)\s*\|\s*([A-Za-z0-9_.-]+)\]\(([^)]+)\)/g

export function splitTextByInlineCitations(
  text: string
): Array<{ type: 'text'; value: string } | { type: 'citation'; token: ParsedInlineCitationToken }> {
  const segments: Array<
    { type: 'text'; value: string } | { type: 'citation'; token: ParsedInlineCitationToken }
  > = []

  let lastIndex = 0
  let match: RegExpExecArray | null
  const regex = new RegExp(INLINE_CITATION_RE.source, 'g')

  while ((match = regex.exec(text)) !== null) {
    if (match.index > lastIndex) {
      segments.push({
        type: 'text',
        value: text.slice(lastIndex, match.index),
      })
    }
    segments.push({
      type: 'citation',
      token: {
        rawMatch: match[0],
        ticker: match[1].trim(),
        fiscalYear: Number(match[2]),
        sectionLabel: match[3].trim(),
        chunkId: match[4].trim(),
        url: match[5].trim(),
      },
    })
    lastIndex = regex.lastIndex
  }

  if (lastIndex < text.length) {
    segments.push({
      type: 'text',
      value: text.slice(lastIndex),
    })
  }

  return segments
}
